//! SMOOTHINT2 - smooth nonuniformly sampled interfaces by damped least squares.
//! Port of par/main/smoothing/smoothint2.c (Revision 1.11).
//! Credits: CWP: Zhenyue Liu, Jan 1994.
//! Reference: Liu, Zhenyue, 1994, Velocity smoothing: theory and implementation,
//! Project Review, 1994, Consortium Project on Seismic Inverse Methods
//! for Complex Stuctures (in review).

use oxwave_core::prelude::*;
use oxwave_f_smooth::*;

/// Self-documentation, byte-identical to the C `sdoc[]` array.
#[rustfmt::skip]
const SDOC: &[&str] = &[
    " \t\t\t\t\t\t\t\t\t",
    " SMOOTHINT2 --- SMOOTH non-uniformly sampled INTerfaces, via the damped",
    "  \t\tleast-squares technique\t\t\t\t\t",
    " \t\t\t\t\t\t\t\t\t",
    "  smoothint2 <input ninf= >output [optional parameters]\t\t",
    " \t\t\t\t\t\t\t\t\t",
    " Required Parameters:\t\t\t\t\t\t\t",
    " <input                 file containing original interfaces\t\t",
    " >output                file containing smoothed interfaces\t \t",
    " \t\t\t\t\t\t\t\t\t",
    " Optional Parameters:\t\t\t\t\t\t\t",
    " ninf=5                number of interfaces  \t\t\t\t",
    " r=100\t\t\tsmoothing parameter \t\t\t\t",
    " npmax=101\t\tmaximum number of points in interfaces\t\t",
    " \t\t\t\t\t\t\t\t\t",
    " Notes:\t\t\t\t\t\t\t\t",
    " The input file is an ASCII file. Each interface is represented by pairs",
    " (non-uniform sampling) of x and z values, with one pair of values on\t",
    " each line, separated by spaces or tabs. Each interface is separated with",
    " an entry with a large negative z value for example: 1.0     -9999.\t",
    " There is no entry for the surface. The surface is assumed to be flat  ",
    " with z=0.\t\t\t\t\t\t\t\t",
    " This is similar to a CSHOT model file without a surface entry and\t",
    " without comments.\t\t\t\t\t\t\t",
    " \t\t\t\t\t\t\t\t\t",
    " The smoothing method is analogous to a moving window averaging process",
    " (but not the same) with the parameter \"r\" being analogous to the \"width\"",
    " of the window. Thus, the size of \"r\" must be chosen to by compatible",
    " with the scale (wavelengths) of the variations of the interfaces in the",
    " model being smoothed.\t\t\t\t\t\t\t",
    " \t\t\t\t\t\t\t\t\t",
    " Example using the test data set generated by unif2: \t\t\t",
    " unif2 tfile=tfilename\t\t\t\t\t\t\t",
    " Compare the unsmoothed interface model:\t\t\t\t",
    " unif2 < tfilename method=interpolation_method |\t\t\t",
    "\t \t\t\tpsimage n1=100 n2=100 d1=10 d2=10 | ...\t",
    " To the smoothed interface model:\t\t\t\t\t",
    " smoothint2 r=100 < tfilename | unif2 method=interpolation_method |\t",
    "\tpsimage n1=100 n2=100 d1=10 d2=10 | ...\t\t\t\t",
    "   \t\t\t\t\t\t\t\t\t",
];

fn main() {
    let argv = args();
    let mut ninf: i32 = 0;
    let mut npmax: i32 = 0;
    let mut r: f32 = 0.0;

    /* hook up getpar */
    initargs(&argv);
    requestdoc(0, SDOC);

    /* get parameters */
    if getparint("ninf", &mut ninf) == 0 {
        ninf = 5;
    }
    if getparint("npmax", &mut npmax) == 0 {
        npmax = 101;
    }
    if getparfloat("r", &mut r) == 0 {
        r = 0.0;
    }

    checkpars();

    // A negative C allocation fails and returns NULL. No array is accessed:
    // the point limit below fires first (or ninf disables the input loop).
    let mut xint = vec![0.0f32; if npmax > 0 { npmax as usize } else { 0 }];
    let mut zint = vec![0.0f32; if npmax > 0 { npmax as usize } else { 0 }];
    let input = stdin();

    /* Input x z pairs specifying interfaces and velocity values. */
    for i in 0..ninf {
        let mut j: i32 = -1;
        loop {
            j += 1;
            if j >= npmax {
                err!(
                    "The point number on the %ith interface exceeds %i!",
                    i + 1,
                    npmax
                );
            }
            // scanf stops at the first failed conversion, leaving stored values
            // unchanged. Retain the arrays between interfaces, as in C.
            if let Some(x) = fscanf_f32(&input) {
                xint[j as usize] = x;
                if let Some(z) = fscanf_f32(&input) {
                    zint[j as usize] = z;
                }
            }
            if !(zint[j as usize] > -9999.0) {
                break;
            }
        }
        let npt = j as usize;

        // The current library omits smooth_1's duplicate-coordinate error.
        // Preserve that error before entering the library's numerical routine.
        for j in 0..npt.saturating_sub(1) {
            if xint[j + 1] == xint[j] {
                err!("x-spacing of data values must not be zero!\n");
            }
        }
        smooth_1(&xint[..npt], &mut zint[..npt], r);
        for j in 0..npt {
            printf!("\t%g\t%g\n", xint[j], zint[j]);
        }
        printf!("\t%g\t%g\n", 1.0, -99999.0);
    }

    exit(CWP_Exit());
}
